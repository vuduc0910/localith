use crate::types::CrawlKnowledgeResult;
use crate::util::escape_cell;

fn code_list(items: &[String], separator: &str) -> String {
    items
        .iter()
        .map(|item| format!("`{item}`"))
        .collect::<Vec<_>>()
        .join(separator)
}

fn push_bullets(lines: &mut Vec<String>, title: &str, items: &[String]) {
    if items.is_empty() {
        return;
    }
    lines.push(format!("**{title}:**"));
    lines.extend(items.iter().map(|item| format!("- {item}")));
    lines.push(String::new());
}

/// Renders the knowledge of every screen as a readable Markdown guide.
pub fn build_knowledge_markdown(knowledge: &CrawlKnowledgeResult) -> String {
    let mut lines: Vec<String> = vec![
        "# Application Screen Knowledge & Keywords Report".into(),
        String::new(),
        format!("- **Target:** {}", knowledge.start_url),
        format!("- **Generated:** {}", knowledge.generated_at),
        format!("- **Model:** {}", knowledge.ollama_model),
        format!("- **Total Unique Screens:** {}", knowledge.total_screens),
        format!(
            "- **Group Pattern Screens:** {}",
            knowledge.total_pattern_groups
        ),
        String::new(),
        "## Global Domain Keywords".into(),
        String::new(),
        if knowledge.global_keywords.is_empty() {
            "—".into()
        } else {
            code_list(&knowledge.global_keywords, " • ")
        },
        String::new(),
        "## Screens Summary".into(),
        String::new(),
        "| # | Screen Name | Type | Pattern / URL | Group? | Top Keywords |".into(),
        "|---:|---|---|---|:---:|---|".into(),
    ];

    for (index, screen) in knowledge.screens.iter().enumerate() {
        let top_keywords = screen
            .keywords
            .iter()
            .take(4)
            .cloned()
            .collect::<Vec<_>>()
            .join(", ");
        lines.push(format!(
            "| {} | **{}** | {} | `{}` | {} | {} |",
            index + 1,
            escape_cell(&screen.screen_name),
            escape_cell(&screen.screen_type),
            escape_cell(&screen.pattern),
            if screen.is_pattern_group {
                "✓"
            } else {
                "—"
            },
            escape_cell(&top_keywords)
        ));
    }

    lines.extend(["", "---", "", "## Screen Details", ""].map(String::from));

    for screen in &knowledge.screens {
        lines.extend([
            format!("### {}", screen.screen_name),
            String::new(),
            format!("- **Pattern / URL:** `{}`", screen.pattern),
            format!("- **Screen Type:** `{}`", screen.screen_type),
            format!(
                "- **Pattern Group:** {}",
                if screen.is_pattern_group {
                    "Yes (parameterized template)"
                } else {
                    "No (static page)"
                }
            ),
            format!("- **Purpose:** {}", screen.purpose),
            format!("- **Summary:** {}", screen.summary),
            String::new(),
        ]);

        push_bullets(&mut lines, "Key Workflows", &screen.key_workflows);
        push_bullets(&mut lines, "Data Entities & Models", &screen.data_entities);
        push_bullets(
            &mut lines,
            "Key UI Components & Sections",
            &screen.ui_components,
        );

        if !screen.keywords.is_empty() {
            lines.push("**Keywords:**".into());
            lines.push(code_list(&screen.keywords, ", "));
            lines.push(String::new());
        }

        if !screen.sample_urls.is_empty() {
            lines.push(format!(
                "<details><summary>Sample URLs ({})</summary>",
                screen.sample_urls.len()
            ));
            lines.push(String::new());
            lines.extend(screen.sample_urls.iter().map(|url| format!("- {url}")));
            lines.extend(["", "</details>", ""].map(String::from));
        }

        lines.extend(["---", ""].map(String::from));
    }

    lines.extend(
        [
            "## Files",
            "",
            "- `knowledge.json`: complete machine-readable knowledge and keywords schema",
            "- `knowledge.md`: this human-readable architectural screen guide",
            "- `screens/*.json`: per-screen detailed knowledge artifact files",
            "",
            "_Generated by Local Website Scanner Knowledge Engine._",
            "",
        ]
        .map(String::from),
    );

    lines.join("\n")
}
